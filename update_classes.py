def update_file(filepath, content, is_iast=False):
    with open(filepath, 'r') as f:
        data = f.read()
    
    parts = data.split('---')
    frontmatter = parts[1]
    
    lines = content.strip().split('\\n')
    lines = [line.strip() for line in lines if line.strip()]
    formatted_content = '<br><br>'.join(lines)
    
    if is_iast:
        formatted_content = transliterate(formatted_content, DEVANAGARI, IAST)
        
    # use repr to escape quotes properly for yaml, then remove outer quotes and add double quotes
    formatted_content_yaml = formatted_content.replace('"', '\\"')
    
    if 'source_text_content:' in frontmatter:
        # Replace existing
        frontmatter = re.sub(r'source_text_content:\s*".*?"', f'source_text_content: "{formatted_content_yaml}"', frontmatter, flags=re.DOTALL)
    else:
        # Append
        frontmatter = frontmatter.rstrip() + f'\\nsource_text_content: "{formatted_content_yaml}"\\n'
        
    new_data = f"---{frontmatter}---" + "---".join(parts[2:])
    with open(filepath, 'w') as f:
        f.write(new_data)

